#!/usr/bin/env python3
"""Writes the colors of an asset catalog as Swift code, for a build without Xcode (build_app.sh).

The asset catalog compiler (actool) ships only with Xcode, so a Command Line Tools build has no
Assets.car and Color("Name") finds nothing. This writes AssetCatalogColor.named("Name") with the same
sRGB values, light and dark, and stops on anything it does not handle (other color spaces,
high-contrast variants), so that a new kind of color is not silently dropped.

Usage: gen_asset_colors.py <Assets.xcassets> <output .swift>
"""

import json
import pathlib
import sys

catalog = pathlib.Path(sys.argv[1])
out = pathlib.Path(sys.argv[2])


def component(value: str) -> float:
    value = value.strip()
    if value.lower().startswith("0x"):
        return int(value, 16) / 255
    if "." in value:
        return float(value)
    return int(value) / 255


def rgba(name: str, entry: dict) -> tuple:
    color = entry["color"]
    if color.get("color-space") != "srgb":
        raise SystemExit(f"{name}: unsupported color space {color.get('color-space')}")
    c = color["components"]
    return (component(c["red"]), component(c["green"]), component(c["blue"]), float(c["alpha"]))


cases = []
for colorset in sorted(catalog.glob("*.colorset")):
    name = colorset.stem
    light = dark = None
    for entry in json.loads((colorset / "Contents.json").read_text())["colors"]:
        if entry.get("idiom") != "universal":
            raise SystemExit(f"{name}: unsupported idiom {entry.get('idiom')}")
        appearances = entry.get("appearances", [])
        if not appearances or appearances == [{"appearance": "luminosity", "value": "light"}]:
            light = rgba(name, entry)
        elif appearances == [{"appearance": "luminosity", "value": "dark"}]:
            dark = rgba(name, entry)
        else:
            raise SystemExit(f"{name}: unsupported appearances {appearances}")
    if light is None:
        raise SystemExit(f"{name}: no light (any appearance) variant")
    dark = dark or light
    literal = lambda t: "(" + ", ".join(f"{v:.6f}" for v in t) + ")"
    cases.append(f'        case "{name}": ({literal(light)}, {literal(dark)})')

out.write_text(f"""// Generated by Tools/release/support/gen_asset_colors.py from Assets.xcassets for a build without
// Xcode: the asset catalog compiler (actool) ships only with Xcode, so these are the catalog's sRGB
// values, light and dark, as code.
import AppKit
import SwiftUI

enum AssetCatalogColor {{
    private typealias RGBA = (CGFloat, CGFloat, CGFloat, CGFloat)

    private static func variants(_ name: String) -> (light: RGBA, dark: RGBA) {{
        switch name {{
{chr(10).join(cases)}
        default: fatalError("No color named \\(name) in the asset catalog")
        }}
    }}

    static func named(_ name: String) -> Color {{
        let (light, dark) = variants(name)
        return Color(nsColor: NSColor(name: NSColor.Name(name)) {{ appearance in
            let c = appearance.bestMatch(from: [.aqua, .darkAqua]) == .darkAqua ? dark : light
            return NSColor(srgbRed: c.0, green: c.1, blue: c.2, alpha: c.3)
        }})
    }}
}}
""")
print(f"{len(cases)} colors from {catalog.name}")
